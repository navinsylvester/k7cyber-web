import type { Payload, PayloadRequest } from 'payload'

/* Sample Threat Reports so the section can be shown before the real library arrives. Each gets a small
   placeholder PDF generated here; replace them from the admin when the real reports are uploaded. */
const pdf = (title: string): Buffer => {
  const text = `BT /F1 24 Tf 72 720 Td (${title.replace(/[()\\]/g, '')}) Tj ET\nBT /F1 12 Tf 72 690 Td (Placeholder PDF generated by the K7 site seed.) Tj ET`
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${text.length} >>\nstream\n${text}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ]
  let out = '%PDF-1.4\n'
  const offsets: number[] = []
  objs.forEach((o, i) => {
    offsets.push(out.length)
    out += `${i + 1} 0 obj\n${o}\nendobj\n`
  })
  const xref = out.length
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('') + `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`
  return Buffer.from(out, 'latin1')
}

const SAMPLE = [
  { period: 'Q2 2026', range: 'April to June', publishedAt: '2026-07-28', gated: true, summary: 'The quarter’s detections across consumer and enterprise endpoints: the malware families that led, the ways in, and how the picture shifted by region and platform.' },
  { period: 'Q1 2026', range: 'January to March', publishedAt: '2026-04-30', gated: false, summary: 'Quarterly view of what K7 Labs detected and blocked, with notes on ransomware, scam campaigns and mobile threats.' },
  { period: 'Annual 2025', range: 'January to December', publishedAt: '2026-02-12', gated: true, summary: 'The full year in one report: long-running trends, the year’s most persistent families, and what they suggest for the year ahead.' },
  { period: 'Q3 2025', range: 'July to September', publishedAt: '2025-10-31', gated: false, summary: 'Quarterly view of detections across endpoints, with a focus on credential theft and abuse of legitimate tools.' },
]

export const seedReports = async ({ payload, req }: { payload: Payload; req: PayloadRequest }): Promise<void> => {
  const existing = await payload.count({ collection: 'threat-reports', req })
  if (existing.totalDocs > 0) {
    payload.logger.info('Threat reports already present; leaving them alone.')
    return
  }
  for (const r of SAMPLE) {
    const name = `K7-Cyber-Threat-Monitor-${r.period.replace(/\s+/g, '-')}.pdf`
    const data = pdf(`K7 Cyber Threat Monitor, ${r.period}`)
    const file = await payload.create({ collection: 'report-files', req, data: { title: `Cyber Threat Monitor ${r.period}` }, file: { data, mimetype: 'application/pdf', name, size: data.length } })
    await payload.create({
      collection: 'threat-reports',
      req,
      data: {
        title: 'Cyber Threat Monitor Report',
        slug: `cyber-threat-monitor-${r.period.toLowerCase().replace(/\s+/g, '-')}`,
        reportType: 'Cyber Threat Monitor Report',
        period: r.period,
        periodRange: r.range,
        publishedAt: r.publishedAt,
        year: Number(r.period.slice(-4)),
        summary: r.summary,
        pdf: file.id,
        gated: r.gated,
        _status: 'published',
      },
    })
    payload.logger.info(`Seeded report ${r.period}`)
  }
}
